-- game Lua numbers are float32, exact only below 2^24, and so is what memreader passes: a larger one goes
-- in two parts, the high one a multiple of 0x10000 (at most 24 significant bits), the low one under 0x10000
function M.split(n)
	local lo = n % 0x10000
	return n - lo, lo
end

-- the carrier: one 32-bit word that rides a forged engine command, so a state change travels in the queue.
-- Bits 31-24 magic 0xD7 (a large negative float; vanilla reload times there are 0.2 and -1.0), 23-20 op,
-- 19-16 flags (1 shots, 2 charge), 15-0 the man's id. Kept as two u16 halves because a u32 above 2^24 is not
-- exact in float32, so the word is never one Lua number and the arithmetic below stays under 2^16.
local OP_NAMES = {"GUARD_ON", "GUARD_OFF", "DISARM", "ARM", "HELLO"}
M.OPS = {}
for n, name in ipairs(OP_NAMES) do M.OPS[name] = n end
local CARRIER_MAGIC = 0xD7
-- HELLO's 16 bits are the handshake's protocol version (15-8) and the sender's player slot (7-0), one bit of the block's
-- 32-bit mask (M.handshake). A HELLO of another version is not counted, here or in the cave (HELLO_VERSION in
-- tools/third_person_cave.py, whose agreement run ties the two): raise it when two builds of the pack would disagree.
-- 2 since 2026-10-22: version 1's slot was an army's place, and a machine of each would read one bit as two things
local HELLO_VERSION, HELLO_SLOTS = 2, 32
M.HELLO_VERSION = HELLO_VERSION
-- how long a handshake under way may take before the player is told and the missing players logged, in model ms. From a
-- press it takes this machine's next callback, one queue delay, the peer's callback, a second delay and one more callback:
-- two delays and 300 ms. The delay is unmeasured (the record's item 2; the simulation runs 200 ms), so 5 s allows 2.3 s a
-- trip. A peer's copy table adds nothing, inferred: every machine builds it inside the "Deployed" callback, and nobody can
-- press before their own. Longer and a player left with no answer presses again, which does nothing while it waits
-- (main.lua)
local HELLO_WAIT = 5000

-- hi, lo of the word; an unknown op or an id outside 0..65535 is an error, never a wrap onto another man. HELLO's id is
-- the player slot, refused past the mask, never wrapped onto another player
function M.carrier(op, id, flags)
	local n = M.OPS[op]
	if not n then error("carrier: unknown op " .. tostring(op), 2) end
	local top = op == "HELLO" and HELLO_SLOTS - 1 or 0xFFFF
	if type(id) ~= "number" or id ~= math.floor(id) or id < 0 or id > top then
		error("carrier: id " .. tostring(id) .. " does not fit " .. (op == "HELLO" and "the army mask" or "16 bits"), 2)
	end
	if op == "HELLO" then id = HELLO_VERSION * 256 + id end
	flags = flags or {}
	return CARRIER_MAGIC * 256 + n * 16 + (flags.shots and 1 or 0) + (flags.charge and 2 or 0), id
end

-- {op, id, shots, charge} from the halves, nil when the magic is absent or the op is not one of ours; a HELLO's id is its
-- player slot, and one of another version or past the mask is nil. Takes any pair of u16s because it is fed the bits of
-- arbitrary floats
function M.uncarrier(hi, lo)
	if math.floor(hi / 256) ~= CARRIER_MAGIC then return nil end
	local op = OP_NAMES[math.floor(hi / 16) % 16]
	if not op then return nil end
	if op == "HELLO" then
		if math.floor(lo / 256) ~= HELLO_VERSION or lo % 256 >= HELLO_SLOTS then return nil end
		lo = lo % 256
	end
	local f = hi % 16
	return {op = op, id = lo, shots = f % 2 == 1, charge = math.floor(f / 2) % 2 == 1}
end

-- ATTACK_1-10, MOVING_, JUMPING_ and FLY_ATTACK_1-10 (484-503: FLY_ATTACK_8-10 were left in until 2026-10-19), RIDER_ and
-- RIDER_FLY_ATTACK_1-10
local function is_attack(s) return s >= 454 and s <= 463 or s >= 484 and s <= 503 or s >= 1901 and s <= 1950 end
-- one man of a regiment: his regiment's volleys too (2026-10-19, its fire at will left alone: he aimed and fired with
-- it). The aim, fire and reload clips, as combat.lua's shooting()
local function is_shot(s) return s >= 1547 and s <= 1599 or s >= 949 and s <= 952 or s >= 2104 and s <= 2116 end

-- Multiplayer's sending rules, pure (no mr), so the harness's fake platform runs these same lines. out.move / halt /
-- follow / carrier / play push one queued command for a body (his mount, or him) and say whether it went; key(body) is
-- one value per body. The engine keeps one parked action per man and the later command wins
-- (MP_FEASIBILITY_20261021_THIRD_PERSON.md, "The overrides, live"): a body gets one action a tick, and none from a
-- clip's send until it is reported or its caller gives up on it (the record's Ruling 19: the queue's delay cancels, a
-- later command arrives as far behind the clip as it was sent), so a step or a turn never replaces a clip still waiting
-- in his queued slot (a block holds one back, a melee without the gate too). The cost: a swing is not re-aimed in that
-- window. What is marked sent is only what went, so a lost one goes again.
-- reset(): the session is over, the next hold stops him anew
function M.net_rules(P, out, key)
	local R = {}
	local took, held, faced, kind, clip = {}, {}, {}, {}, {}
	local guards = {} -- {k, id} for each body a GUARD_ON went for: its GUARD_OFF goes by that id, nothing read off him
	local function body(m) return P.mount(m) or m end
	local function free(k) -- this tick's one action for him, if it is not taken and no clip of his is in flight
		local t = bm:time_elapsed_ms()
		local c = clip[k]
		if c then
			if t < c.till and P.anim_slot(c.m) ~= c.slot then return false end
			clip[k] = nil
		end
		if took[k] == t then return false end
		took[k] = t
		return true
	end
	-- a clip. His own swing or shot goes with an ARM ahead of it in the queue, so it starts armed on every machine (on the
	-- copy the engine finds no clip to start). till: the model s its caller gives up on seeing it; none, its tick alone
	function R.play(m, slot, mask, till)
		if is_attack(slot) or is_shot(slot) then R.arm(m) end
		if not out.play(m, slot, mask) then return false end
		local k = key(body(m))
		took[k], clip[k] = bm:time_elapsed_ms(), till and {m = m, slot = slot, till = till * 1000} or nil
		return true
	end
	-- each frame, for the man played: a clip once seen ends its block, though nothing was sent for him while it played
	-- (without this, a swing that played and ended blocked him to its give-up, 3.2 s from the click)
	function R.watch(m)
		if not m then return end
		local k = key(body(m))
		local c = clip[k]
		if c and P.anim_slot(c.m) == c.slot then clip[k] = nil end
	end
	function R.steer(m, x, z, run, yaw, scale)
		local b = body(m)
		local k = key(b)
		if not free(k) then return end
		if out.move(b, x, z, run, yaw, scale) then held[k], faced[k] = nil, nil end
	end
	function R.face(m, yaw)
		if not yaw then return end
		local b = body(m)
		local k = key(b)
		if faced[k] == yaw or not free(k) then return end
		if out.follow(b, yaw) then faced[k] = yaw end
	end
	function R.hold(m, x, z, yaw)
		local b = body(m)
		local k = key(b)
		if held[k] then return R.face(b, yaw) end
		if not free(k) then return end
		if out.halt(b, x, z) then held[k], faced[k] = true, nil end
	end
	function R.guard(m)
		local b = body(m)
		local k = key(b)
		for _, g in ipairs(guards) do if g.k == k then return true end end
		local ok, id = out.carrier(b, "GUARD_ON")
		if ok then guards[#guards + 1] = {k = k, id = id} end
		return true
	end
	-- every entry a GUARD_ON claimed, by its id: the man may be dead, his model gone
	function R.unguard()
		local left = {}
		for _, g in ipairs(guards) do
			if not out.carrier(nil, "GUARD_OFF", nil, g.id) then left[#left + 1] = g end
		end
		guards = left
	end
	function R.reset() held, faced = {}, {} end
	-- the horse's and the rider's, as P.disarm; none sent is armed
	local function set(x, op, flags)
		local k = key(x)
		local want = op == "DISARM" and ((flags.shots and "s" or "") .. (flags.charge and "c" or "") .. "d") or nil
		if kind[k] ~= want and out.carrier(x, op, flags) then kind[k] = want end
	end
	function R.disarm(m, shots, charge)
		local flags = {shots = shots == true, charge = charge == true}
		if P.mount(m) then set(P.mount(m), "DISARM", flags) end
		set(m, "DISARM", flags)
	end
	function R.arm(m)
		if P.mount(m) then set(P.mount(m), "ARM", {}) end
		set(m, "ARM", {})
	end
	return R
end

-- The battle's network players, read off CA's player list (CcoMultiplayerRoot.PlayerList, through the CCO global function
-- MultiplayerRootContext; CA's own battle UI reads it there, mp_team_list.twui.xml): {id, name, me, watching} for each one
-- online, in the list's order, or nil and why it could not be read. id is CA's "unique mp client id"; watching, a spectator
-- or a partner given units to play (IsPassiveParticipant, CA: "spectating but can receive units from active players to
-- join in"). Pure but for common.get_context_value, which the harness answers by expression
local PLAYERS = "MultiplayerRootContext.PlayerList"
function M.players()
	local function v(expr) return common.get_context_value("CcoBattleRoot", "", PLAYERS .. expr) end
	local ok, res = pcall(function()
		local n = v(".Size")
		if type(n) ~= "number" then return "its size read " .. tostring(n) end
		local t = {}
		for i = 0, n - 1 do
			local at = ".At(" .. i .. ")."
			local id = v(at .. "Id")
			if type(id) ~= "string" or id == "" then return "player " .. i .. "'s id read " .. tostring(id) end
			if v(at .. "IsOnline") ~= false then
				t[#t + 1] = {id = id, name = tostring(v(at .. "Name") or ""), me = v(at .. "IsLocalPlayer") == true,
					watching = v(at .. "IsSpectating") == true or v(at .. "IsPassiveParticipant") == true}
			end
		end
		return t
	end)
	if not ok then return nil, "it threw: " .. tostring(res) end
	if type(res) == "string" then return nil, res end
	return res
end

-- The HELLO handshake (MP_FEASIBILITY_20261021_THIRD_PERSON.md, Rulings 25, 26 and 30), pure (no mr), so the harness's
-- fake platform runs these same lines. Net play and the order gate wait until every machine in the battle has said HELLO:
-- a machine without the pack, memreader Plus or this build never does, and one machine's gate and commands alone desync
-- the battle. Every player counts, a spectator and a partner watching with units given to them too, since each one's
-- machine runs the battle (Ruling 30: until 2026-10-22 human armies were counted, so a battle against the AI never started,
-- nor one a partner joined on the player's side). Nothing is sent until someone wants to play: a machine says HELLO once
-- this player has pressed F2 (P.net_asked, main.lua) or another player's HELLO has landed, and only once its copy table is
-- built (P.net_ready), so a HELLO that executed also says that machine's table is there; a lobby where nobody presses F2
-- carries nothing. The carrier cave sets the player's bit on every machine at one tick, and this, run each model tick on
-- every machine (a replay too, Ruling 17), puts the gate in once every player's bit is set: inferred to be the same tick
-- everywhere, since a model callback's place in the tick is untraced (BATTLE_ENGINE_RE.md section 14).
-- hello(slot): push one HELLO, whether it went (one that did not goes again next tick); heard(slot): its bit is set;
-- players(): M.players. A player's slot is their place in the list sorted by client id, so every machine that sees the same
-- players gives each one the same bit. P.net_me is this machine's own entry. HELLO_WAIT model ms after the handshake got
-- under way here P.net_late is set, and P.net_why says why, for main.lua to tell a waiting player: "players", the list
-- cannot be used (P.net_problem); "self", this machine's own HELLO has not landed; "missing", another's has not
-- (P.net_missing, their names). The log names players by slot only: a player posts it, and the names are their friends'.
-- Returns the model callback; a throw in it is logged, never let into CA's timer list
function M.handshake(P, hello, heard, once, players)
	local sent, since
	local function log(tag, text) if once then once(tag, text) end end
	local function list_of(t) return #t > 0 and table.concat(t, ",") or "none" end
	local function step()
		if P.net_play then return end
		local list, why = players()
		local mine, seen, all, watching = nil, {}, {}, {}
		if list then
			table.sort(list, function(a, b) return a.id < b.id end)
			for i, p in ipairs(list) do
				all[i] = i - 1
				if p.watching then watching[#watching + 1] = i - 1 end
				if seen[p.id] then why = "two players share one id" end
				seen[p.id] = true
				if p.me then
					if mine then why = "two players are this machine" end
					mine = i - 1
				end
			end
			-- one player would start this machine alone, and a list that only it is in would too: refused, which is safe,
			-- where starting alone is not
			why = why or #list < 2 and "it names " .. #list .. " player" .. (#list == 1 and "" or "s")
				or #list > HELLO_SLOTS and "it names " .. #list .. " players, past the HELLO mask"
				or not mine and "this machine is not in it" or nil
		end
		P.net_me = not why and list[mine + 1] or nil
		local missing, other = {}, false
		if not why then
			for _, s in ipairs(all) do
				if not heard(s) then missing[#missing + 1] = s elseif s ~= mine then other = true end
			end
		end
		local of = list_of(all) .. " of " .. #all
		if P.net_ready and (P.net_asked or other) then
			if not since and not why then
				log("hello_list", "multiplayer: players " .. of .. ", this machine " .. mine .. ", watching " .. list_of(watching))
			end
			since = since or bm:time_elapsed_ms()
			-- not from a replay, which has its recorded HELLOs; one that cannot say whether it is one sends nothing
			local ok, replay = pcall(function() return bm:is_replay() end)
			if not ok then log("hello_replay", "multiplayer waits: is_replay threw: " .. tostring(replay)) end
			if ok and not replay and not why and not sent then
				local pushed, went = pcall(hello, mine)
				sent = pushed and went or nil
			end
			-- late only with someone missing: a completion in this same step is not late
			if bm:time_elapsed_ms() - since >= HELLO_WAIT and not P.net_late and (why or #missing > 0) then
				P.net_late = true
				if why then
					P.net_why, P.net_problem = "players", why
					log("hello_players", "multiplayer waits: the player list cannot be used: " .. why)
				else
					log("hello_missing", "multiplayer waits: players " .. of .. ", no HELLO from " .. list_of(missing) .. " after "
						.. HELLO_WAIT .. " model ms")
					if not heard(mine) then
						P.net_why = "self"
						log("hello_self", "multiplayer waits: this machine's own HELLO, player " .. mine .. ", has not landed")
					else
						local names = {}
						for _, s in ipairs(missing) do
							local name = list[s + 1].name
							names[#names + 1] = name ~= "" and name or "player " .. (s + 1)
						end
						P.net_why, P.net_missing = "missing", table.concat(names, ", ")
					end
				end
			end
		end
		if why or #missing > 0 then return end
		if not P.gate(true) then log("hello_gate", "multiplayer waits: the order gate did not go in") return end
		P.net_play = true
		log("hello_done", "players " .. of .. " all said HELLO by " .. tostring(bm:time_elapsed_ms()) .. " model ms: the order gate is in")
	end
	return function()
		local ok, err = pcall(step)
		if not ok then log("hello_error", "multiplayer waits: the handshake threw: " .. tostring(err)) end
	end
end

-- net: the battle is multiplayer (bm:is_multiplayer()); once(tag, text): the entry's log-once
function M.build(mr, net, once)
	local P = {features = {input = false, anim = false, wheel = false, men = false, net = false}, problems = {}}
	local base = mr.base
	local function at(p, n)
		if type(n) == "table" then return mr.add(mr.add(p, n[1]), n[2]) end
		local hi, lo = M.split(n)
		return mr.add(mr.add(p, hi), lo)
	end
	local function problem(group, why) P.features[group] = false P.problems[#P.problems + 1] = group .. ": " .. why end
	-- Wine can map imported DLL functions below Windows' usual DLL address range.
	local function sys(p) return p ~= nil and not mr.is_null(p) end

	-- a 32-bit field read as two exact 16-bit halves: read_int32 above 2^24 comes back rounded, and every
	-- RVA in Warhammer3.exe is above it. rva() turns the field straight into a pointer into the image.
	local function u16(p, off) return mr.read_uint16(p, off) end
	local function rva(p, off) return mr.add(mr.add(base, u16(p, off + 2) * 0x10000), u16(p, off)) end
	local function zero32(p, off) return u16(p, off) == 0 and u16(p, off + 2) == 0 end
	local pe = mr.read_int32(base, 0x3c)
	P.build = string.format("%04x%04x", u16(base, pe + 10), u16(base, pe + 8))

	-- imports, parsed from the loaded image so that no build has to store them
	local function upper(c) if c >= 97 and c <= 122 then return c - 32 end return c end
	local function cstr_is(p, s, fold)
		for i = 1, #s do
			local c = mr.read_uint8(p, i - 1)
			if fold then c = upper(c) end
			if c ~= s:byte(i) then return false end
		end
		return mr.read_uint8(p, #s) == 0
	end
	local fn = {}
	local desc = rva(base, pe + 0x90) -- PE32+ import directory: 20-byte descriptors, ended by a null one
	while not zero32(desc, 12) do
		local dll_name = rva(desc, 12)
		for dll, names in pairs(WANT) do
			if not zero32(desc, 0) and cstr_is(dll_name, dll, true) then
				local thunks, iat = rva(desc, 0), rva(desc, 16) -- names (OriginalFirstThunk), addresses (FirstThunk)
				local k = 0
				while not (zero32(thunks, k * 8) and zero32(thunks, k * 8 + 4)) do
					if u16(thunks, k * 8 + 6) < 0x8000 then -- bit 63 clear: imported by name, at hint/name + 2
						local hint = mr.add(rva(thunks, k * 8), 2)
						for _, name in ipairs(names) do
							if not fn[name] and cstr_is(hint, name) then fn[name] = mr.read_pointer(iat, k * 8) end
						end
					end
					k = k + 1
				end
			end
		end
		desc = mr.add(desc, 20)
	end

	-- input --------------------------------------------------------------------------------------------
	for _, name in ipairs({"GetAsyncKeyState", "GetCursorPos", "SetCursorPos", "GetForegroundWindow", "GetClientRect",
		"ClientToScreen", "GetWindowThreadProcessId", "GetCurrentProcessId"}) do
		if not fn[name] or not sys(fn[name]) then problem("input", name .. " not found in the import table") return P end
	end
	P.features.input = true
	local buf, rect, owner = mr.alloc(8), mr.alloc(16), mr.alloc(8)
	local pid = mr.tonumber(mr.call(fn.GetCurrentProcessId, "int32()"))
	-- focused: the foreground window belongs to this process, and it becomes the window looking parks in.
	-- Not a window captured at load: a battle loaded while the game was in the background would never focus.
	function P.focused()
		local w = mr.call(fn.GetForegroundWindow, "pointer()")
		if mr.is_null(w) then return false end
		mr.call(fn.GetWindowThreadProcessId, "int32(pointer, pointer)", w, owner)
		if mr.read_int32(owner, 0) ~= pid then return false end
		P.window = w
		return true
	end
	local function down(vk) return mr.tonumber(mr.call(fn.GetAsyncKeyState, "int16(int32)", vk)) < 0 end
	function P.held(vk)
		if vk == nil then return false end
		if type(vk) == "table" then for _, k in ipairs(vk) do if down(k) then return true end end return false end
		return down(vk)
	end
	local was = {}
	function P.pressed(vk) -- down now and up at this key's last call
		if vk == nil then return false end
		local key = type(vk) == "table" and vk[1] or vk
		local d = P.held(vk)
		local edge = d and not was[key]
		was[key] = d
		return edge
	end
	local cx, cy = 0, 0
	function P.look_begin() -- park the cursor at the window centre
		mr.call(fn.GetClientRect, "int32(pointer, pointer)", P.window, rect)
		mr.write(buf, 0, mr.int32(math.floor(mr.read_int32(rect, 8) / 2)))
		mr.write(buf, 4, mr.int32(math.floor(mr.read_int32(rect, 12) / 2)))
		mr.call(fn.ClientToScreen, "int32(pointer, pointer)", P.window, buf)
		cx, cy = mr.read_int32(buf, 0), mr.read_int32(buf, 4)
		mr.call(fn.SetCursorPos, "int32(int32, int32)", cx, cy)
	end
	function P.look_delta() -- pixels since the last park, then parked again
		mr.call(fn.GetCursorPos, "int32(pointer)", buf)
		local dx, dy = mr.read_int32(buf, 0) - cx, mr.read_int32(buf, 4) - cy
		if dx ~= 0 or dy ~= 0 then mr.call(fn.SetCursorPos, "int32(int32, int32)", cx, cy) end
		return dx, dy
	end
	-- no cursor picture: the game's own middle-button release puts its cursor back, and no cinematic UI call hides it
	-- again (measured 2026-10-21, GetCursorInfo under real clicks); SetCursor(NULL) did, at once. Called each frame the
	-- mouse is parked; stateless, so a battle quit mid-look leaves nothing to undo (memory wh3-hide-cursor-route)
	function P.hide_cursor() if fn.SetCursor then mr.call(fn.SetCursor, "pointer(pointer)", nil) end end

	-- the animation command ---------------------------------------------------------------------------
	local A
	local row = BUILDS[P.build]
	P.features.steer = row ~= nil and row.walk_a ~= nil and row.walk_b ~= nil and row.walk_start ~= nil and row.walk_speed ~= nil
		and row.walk_stop ~= nil
	local walk_a = P.features.steer and at(base, row.walk_a)
	local walk_b = P.features.steer and at(base, row.walk_b)
	local walk_speed = P.features.steer and at(base, row.walk_speed)
	if row then
		A = {cmd_type = at(base, row.cmd_type), battle = at(base, row.battle), push = at(base, row.cmd_push),
			sub = row.battle_sub, gate_a = row.gate_a, gate_b = row.gate_b, queue = row.queue}
		P.source = "known build"
	end
	-- an unknown build searches at the first check, not here: a search that throws must cost the swing,
	-- never the load (main.lua turns a check that throws into a failed check)
	local function search()
		local hit, count = mr.find_pattern(PATTERN)
		if count ~= 1 then return end
		local function rip(o) -- a signed 32-bit displacement, in exact halves like rva()
			local hi = u16(hit, o + 2)
			if hi >= 0x8000 then hi = hi - 0x10000 end
			return mr.add(mr.add(mr.add(hit, o + 4), hi * 0x10000), u16(hit, o))
		end
		A = {cmd_type = rip(3), battle = rip(0x23), push = rip(0x4d), sub = mr.read_int32(hit, 0x2a),
			gate_a = mr.read_int32(hit, 0x31), gate_b = mr.read_int32(hit, 0x3a), queue = mr.read_int32(hit, 0x48)}
		P.source = "byte pattern"
	end
	local cmd = mr.alloc(32)
	local function battle_obj()
		local g = mr.read_pointer(A.battle, 0)
		if mr.is_null(g) then return nil end
		local b = mr.read_pointer(g, A.sub)
		if mr.is_null(b) then return nil end
		return b
	end
	function P.check_anim()
		if not A then search() end
		if not A then problem("anim", "unknown build " .. P.build .. " and the command pattern did not match once") return false, P.problems[#P.problems] end
		local b = battle_obj()
		if not b then problem("anim", "the battle object is not reachable") return false, P.problems[#P.problems] end
		local ga, gb = mr.read_uint8(b, A.gate_a), mr.read_uint8(b, A.gate_b)
		if ga > 1 or gb > 1 then problem("anim", "gate bytes read " .. ga .. " and " .. gb) return false, P.problems[#P.problems] end
		if mr.is_null(mr.read_pointer(b, A.queue)) then problem("anim", "the command queue is null") return false, P.problems[#P.problems] end
		P.features.anim = true
		return true
	end
	-- a man's animation fragment, +0x308 (what P.has_slot reads): a u16 clip index per slot from +0x50, 0xffff for none,
	-- one per regiment and skeleton. P.disarm points the man played alone at a copy with no attack clips
	local FRAG, FRAG_COPY = 0x308, 0x50 + 6004 * 2 -- a fragment is 0x1284; a slot scan read 6000 slots past each safely
	local copy_of, orig_of, shots_of, charge_of = {}, {}, {}, {} -- by address: the fragment -> its copy (per kind), and back; a copy's kind
	local function unpoint(x)
		local o = orig_of[mr.tostring(mr.read_pointer(x, FRAG))]
		if o then mr.write(x, FRAG, o) end
	end
	function P.play(m, slot, mask) -- mask 6 holds a full-body clip even when it has no event metadata
		if not P.features.anim then return false end
		local b = battle_obj()
		if not b or mr.read_uint8(b, A.gate_a) ~= 0 or mr.read_uint8(b, A.gate_b) ~= 0 then return false end
		-- his own swing or shot, on his own table: on the copy the engine finds no clip. In multiplayer the ARM carrier ahead of
		-- the clip does it on every machine (M.net_rules R.play); a write here would be this machine's alone
		if (is_attack(slot) or is_shot(slot)) and not P.features.net then unpoint(m) end
		mr.write(cmd, 0, A.cmd_type)
		mr.write(cmd, 8, m)
		mr.write(cmd, 0x10, mr.uint16(slot))
		mr.write(cmd, 0x12, mr.uint8(0))
		mr.write(cmd, 0x14, mr.uint32(mask or 0))
		mr.call(A.push, "uint8(pointer, pointer)", mr.read_pointer(b, A.queue), cmd)
		return true
	end
	-- A pushed clip waits in his queued action slot (+0x5c8) until his update (exe+3086f04) runs it, and it resets it
	-- instead on any tick an order reached him (+0x324 not 0); in a melee his regiment orders him every tick (measured
	-- 2026-10-16, probes/zz_tp_melee_spam.lua, Teutogen Guard under two units, a click every 2.4 s): 4 and 0 swings of
	-- 10 started. That jump (exe+3087388, to the reset at exe+30873e6) sent to his action update (exe+30873dc) instead:
	-- 10 and 10, in 200-400 ms. Game code, so it runs on the battle thread, with nothing to race.
	-- ponytail: while it is in, a queued action on ANY man beats that tick's order; in a battle the pack plays only
	-- P.play queues one. A per-man check needs a code cave. Multiplayer puts it in once every player's HELLO has landed
	-- (M.handshake) and keeps it to the battle's end: single player puts it in at a start and out at the stop (main.lua)
	local GATE = {0x44, 0x38, 0xbf, 0xf8, 0x06, 0, 0, 0x75, 0x09, 0x44, 0x38, 0xbf, 0, 0x06, 0, 0, 0x75}
	local gate = row and row.queued_gate and mr.patch and at(base, row.queued_gate)
	local function gate_bytes(jump) local t = {unpack(GATE)} t[#t + 1] = jump return string.char(unpack(t)) end
	local reset, update = gate_bytes(0x5c), gate_bytes(0x52)
	function P.gate(on) -- memreader's patch writes only over the bytes it expects
		if not gate then return false end
		if on then return mr.patch(gate, reset, update) ~= nil end
		return mr.patch(gate, update, reset) ~= nil
	end
	P.gate(false) -- a battle left while it was in (no stop) left it in
	-- the game's own branch is there, so the gate can go in later: multiplayer's build checks it (install_net). Read, not
	-- patched, so the check never leans on memreader accepting bytes that are already the new ones
	local function gate_out()
		if not gate then return false end
		for i = 1, #reset do if mr.read_uint8(gate, i - 1) ~= reset:byte(i) then return false end end
		return true
	end

	-- The camera's floor (exe+2ebf734 and its siblings) puts the eye at max(A + its minimum, the terrain + its height), A
	-- the height a raycast under the eye finds (exe+2ee841c), which counts a roof or a wall: an eye asked 2 m over the road
	-- under a gatehouse went 18-24 m up, and 4.3 in the open (measured 2026-10-18, probes/zz_tp_cam_sweep.lua; the author:
	-- "if its around a building, it would go way up"). The raycast's entry jumps to the terrain's (exe+2ec2710; both take
	-- the camera and an (x, z) and return a height, side by side in all 18 camera vtables): 2.0 at every point.
	-- ponytail: while it is in, every battle camera ignores buildings; only third person's moves while it is on
	local PROLOGUE = string.char(0x48, 0x8b, 0xc4, 0x48, 0x89) -- mov rax, rsp; mov [rax + 8], rbx: what the jump covers
	local floor_at = row and row.cam_collide and mr.patch and at(base, row.cam_collide)
	local floor_jmp
	if floor_at then
		local rel = row.cam_terrain - row.cam_collide - 5 -- under 2^24 either way, so exact in float32
		local u, t = rel < 0 and -rel - 1 or rel, {0xe9}
		for _ = 1, 4 do local b = u % 256 t[#t + 1] = rel < 0 and 255 - b or b u = (u - b) / 256 end
		floor_jmp = string.char(unpack(t))
	end
	function P.terrain_floor(on) -- on: the camera's floor is the terrain alone
		if not floor_at then return false end
		if on then return mr.patch(floor_at, PROLOGUE, floor_jmp) ~= nil end
		return mr.patch(floor_at, floor_jmp, PROLOGUE) ~= nil
	end
	P.terrain_floor(false)

	-- the mailbox ---------------------------------------------------------------------------------------
	-- The battle runs on worker threads while the script runs (docs/BATTLE_ENGINE_RE.md section 9), and the engine's stop
	-- and its walk builder both destroy the command at +0x330 that a worker may be running: called from here they crashed
	-- the game (exe+7AB1DA, 2026-10-17, a command's destructor reading FFFFFFFFFFFFFFFF, the log's last line the guard;
	-- exe+305B39A, 2026-10-16). The cave at the top of his update (CAVE, tools/third_person_cave.py) makes the same calls
	-- on the battle thread, from requests posted into its block; the script only writes the block. A cave stays for the
	-- session, so a later battle finds it there and reads its block back out of its first instruction
	local update = P.features.steer and row.update and at(base, row.update)
	local block
	local function zero(off, n) for o = off, off + n - 4, 4 do mr.write(block, o, mr.uint32(0)) end end
	local function fail(why) problem("mailbox", why) return false, P.problems[#P.problems] end
	function P.check_mailbox()
		if block then return true end
		if not update then return fail("his update is not known on build " .. P.build) end
		if not (mr.patcher and mr.game_alloc and mr.hook_info and mr.read_original) then return fail("memreader Plus has no patcher: update it") end
		if mr.read_original(update, 0, #CAVE_SITE) ~= string.char(unpack(CAVE_SITE)) then return fail("his update is not the code the cave expects") end
		local info = mr.hook_info(update)
		local b = info and info.kind == "cave" and mr.read_pointer(info.cave, CAVE_BLOCK) or mr.game_alloc(MB.size)
		local bytes, hex = {unpack(CAVE)}, mr.tostring(b)
		for i = 0, 7 do bytes[CAVE_BLOCK + i + 1] = tonumber(hex:sub(15 - 2 * i, 16 - 2 * i), 16) end -- low byte first
		local cave, why = mr.patcher("derpy_tp"):cave("mailbox", update, string.char(unpack(bytes)))
		if not cave then return fail("the cave: " .. tostring(why)) end
		block = b
		-- nobody, no request: a block an earlier battle left may hold both. The functions are written over, never zeroed:
		-- a cave already past its match calls through them (FUNCS: the carrier cave, installed for the session, jumps
		-- through skip and calls map_lookup, which sit past buf for that reason)
		zero(MB.man, 8)
		zero(MB.guard, MB.buf - MB.guard)
		zero(MB.buf, 0x60)
		zero(MB.guards, MB.size - MB.guards) -- the guard entries go with their count
		for _, k in ipairs({"walk_a", "move_a", "move_b", "melee", "walk_b", "walk_stop", "walk_start"}) do mr.write(block, MB[k], at(base, row[k])) end
		-- the walk builder's parameter block (native constructor 3249284): straight path, no borrowed path pointers, movement flags
		mr.write(block, MB.buf + 0x34, mr.uint32(3))
		for _, off in ipairs({0x44, 0x45, 0x4a}) do mr.write(block, MB.buf + off, mr.uint8(1)) end
		P.mailbox, P.features.mailbox = block, true
		return true
	end
	P.check_mailbox()
	local function post(m, field, request)
		mr.write(block, MB.man, m)
		mr.write(block, MB[field], mr.uint32(request))
	end

	-- the wheel: our own DirectInput 8 mouse, one per battle, kept in a global so a reload reuses it -----
	function P.open_wheel()
		local D = _G.DERPY_TP_DI
		if not (D and D.dev) then
			local create = fn.DirectInput8Create
			if not create or not sys(create) then problem("wheel", "DirectInput8Create not imported") return false, P.problems[#P.problems] end
			local m = mr.alloc(160)
			local function bytes(off, t) for i = 1, #t do mr.write(m, off + i - 1, mr.uint8(t[i])) end end
			bytes(0, {0x31, 0x80, 0x79, 0xBF, 0x3A, 0x48, 0xA2, 0x4D, 0xAA, 0x99, 0x5D, 0x64, 0xED, 0x36, 0x97, 0x00}) -- IID_IDirectInput8W
			bytes(16, {0x60, 0x2B, 0x1D, 0x6F, 0xA0, 0xD5, 0xCF, 0x11, 0xBF, 0xC7, 0x44, 0x45, 0x53, 0x54, 0x00, 0x00}) -- GUID_SysMouse
			bytes(32, {0xE2, 0x02, 0x6D, 0xA3, 0xF3, 0xC9, 0xCF, 0x11, 0xBF, 0xC7, 0x44, 0x45, 0x53, 0x54, 0x00, 0x00}) -- GUID_ZAxis
			mr.write(m, 64, mr.add(m, 32)) -- DIOBJECTDATAFORMAT: pguid, dwOfs 0, DIDFT_AXIS | DIDFT_ANYINSTANCE
			mr.write(m, 76, mr.uint32(0x00FFFF03))
			mr.write(m, 96, mr.uint32(32)) -- DIDATAFORMAT: size, object size 24, DIDF_RELAXIS, 4 bytes, 1 object
			mr.write(m, 100, mr.uint32(24))
			mr.write(m, 104, mr.uint32(2))
			mr.write(m, 108, mr.uint32(4))
			mr.write(m, 112, mr.uint32(1))
			mr.write(m, 120, mr.add(m, 64))
			local function method(obj, i) return mr.read_pointer(mr.read_pointer(obj, 0), i * 8) end
			if mr.tonumber(mr.call(create, "int32(pointer, uint32, pointer, pointer, pointer)", base, 0x800, m, mr.add(m, 48), nil)) ~= 0 then
				problem("wheel", "DirectInput8Create failed") return false, P.problems[#P.problems]
			end
			local di = mr.read_pointer(m, 48)
			if mr.tonumber(mr.call(method(di, 3), "int32(pointer, pointer, pointer, pointer)", di, mr.add(m, 16), mr.add(m, 56), nil)) ~= 0 then
				problem("wheel", "CreateDevice failed") return false, P.problems[#P.problems]
			end
			local dev = mr.read_pointer(m, 56)
			if mr.tonumber(mr.call(method(dev, 11), "int32(pointer, pointer)", dev, mr.add(m, 96))) ~= 0 then
				problem("wheel", "SetDataFormat failed") return false, P.problems[#P.problems]
			end
			mr.call(method(dev, 13), "int32(pointer, pointer, uint32)", dev, P.window, 0xA) -- NONEXCLUSIVE | BACKGROUND
			mr.call(method(dev, 7), "int32(pointer)", dev)
			D = {dev = dev, acquire = method(dev, 7), state = method(dev, 9), buf = mr.add(m, 128)}
			_G.DERPY_TP_DI = D
		end
		function P.wheel() -- notches since the last call; re-acquires a lost device
			if mr.tonumber(mr.call(D.state, "int32(pointer, uint32, pointer)", D.dev, 4, D.buf)) ~= 0 then
				mr.call(D.acquire, "int32(pointer)", D.dev)
				return 0
			end
			return mr.read_int32(D.buf, 0) / 120
		end
		P.features.wheel = true
		return true
	end

	-- a unit's men -------------------------------------------------------------------------------------
	local function obj_of(unit) return mr.read_pointer(mr.ud_topointer(unit), 8) end
	function P.models(unit)
		local obj = obj_of(unit)
		local n, data = mr.read_int32(obj, MODELS_N), mr.read_pointer(obj, MODELS_DATA)
		local t = {}
		for k = 0, n - 1 do t[k + 1] = mr.read_pointer(data, k * 8) end
		return t
	end
	function P.model_pos(m) return mr.read_float(m, MODEL_POS), mr.read_float(m, MODEL_POS + 4), mr.read_float(m, MODEL_POS + 8) end
	function P.model_hp(m)
		m = P.mount(m) or m
		return mr.read_int32(m, MODEL_HP), mr.read_int32(m, MODEL_HP_MAX)
	end
	function P.has_slot(m, slot) -- engine lookup exe+1482074; checks the model's active fragment, including mods
		if not P.features.steer then return false end
		local anim = mr.read_pointer(m, FRAG)
		anim = orig_of[mr.tostring(anim)] or anim -- disarmed, he still has his swings
		return not mr.is_null(anim) and mr.read_uint16(anim, 0x50 + slot * 2) ~= 0xffff
	end
	-- RELOAD_1 or nothing: a man without it (a crossbow, a grenadier) reloads on the clock (the author, 2026-10-17: his
	-- raise to aim, taken for his reload, let some ranged units bypass the reload time)
	function P.reload_slot(m)
		if P.has_slot(m, 1564) then return 1564 end
	end
	function P.mount(m)
		if not P.features.steer then return nil end
		local parent = mr.read_pointer(m, 0x2e0) -- rider parent, also followed by native exe+305468c
		if not mr.is_null(parent) then return parent end
	end
	function P.anim_slot(m) -- native wait command exe+325c7ec checks metadata and the body mask
		if mr.is_null(mr.read_pointer(m, 0x898)) and mr.read_int32(m, 0x284) == 0 then return nil end
		return mr.read_uint16(m, 0x278)
	end
	local function heading16(yaw) return math.floor((yaw % (2 * math.pi)) * 0x10000 / (2 * math.pi)) end
	function P.face(m, yaw)
		if not P.features.steer or not yaw then return nil end
		m = P.mount(m) or m
		local angle = heading16(yaw)
		mr.write(m, 0xb0, mr.uint16(angle))
		return angle
	end
	-- the heading P.face writes, read back: radians, the camera's yaw convention
	function P.heading(m)
		if not P.features.steer then return nil end
		m = P.mount(m) or m
		return mr.read_uint16(m, 0xb0) * 2 * math.pi / 0x10000
	end
	function P.place(m, x, z) mr.write(m, MODEL_POS, x) mr.write(m, MODEL_POS + 8, z) end
	-- scale: times the engine's own speed for his gait (a sprint's 1.5). Under his own walk (walk_b) the cave writes the
	-- point, run flag, speed, gait and heading into it, and clears its cached destination (+0x3c0) when one changed; under
	-- anything else it has the engine build a new walk from buf (never a forged vtable) - unless he is already at the
	-- point, where an idle keeps its animations and pending state commands. A regiment walk never followed a point
	-- written into it (measured live 2026-10-14)
	function P.steer(m, x, z, run, yaw, scale)
		m = P.mount(m) or m
		for _, f in ipairs(STEER) do mr.write(m, f[1], x) mr.write(m, f[2], z) end
		if not P.features.steer then return end
		local angle = P.face(m, yaw)
		if not block then return end
		local unit = mr.read_pointer(m, 0x2e8)
		local speed = not mr.is_null(unit) and mr.call(walk_speed, "float(pointer, uint8)", unit, run and 1 or 0)
		if not speed then return end
		if scale then speed = speed * scale end
		local mx, my, mz = P.model_pos(m)
		local b = MB.buf
		mr.write(block, b, x) mr.write(block, b + 4, my) mr.write(block, b + 8, z)
		mr.write(block, b + 0x28, mr.uint32(run and 1 or 0)) mr.write(block, b + 0x2c, speed)
		mr.write(block, b + 0x30, mr.uint16(angle or math.floor((math.atan2(x - mx, z - mz) % (2 * math.pi)) * 0x10000 / (2 * math.pi))))
		mr.write(block, b + 0x46, mr.uint8(run and 1 or 0))
		mr.write(block, b + 0x4c, bm:time_elapsed_ms() / 1000)
		mr.write(block, MB.has_angle, mr.uint8(angle and 1 or 0))
		mr.write(block, MB.near, mr.uint8((x - mx) ^ 2 + (z - mz) ^ 2 <= 0.01 and 1 or 0))
		post(m, "walk", 2)
	end
	-- his own walk ended itself (measured 2026-10-18, a dwarf hold): to a point the pathfinder finds no way to,
	-- exe+3077009 sets his path state (+0x710) to 7 and his walk's update (exe+3262850), with no path of its own, sets the
	-- walk's done byte (+0x10 of it, +0x340 of him). The walk stays on him, and written in place it moves him no more
	function P.walk_ended(m)
		if not P.features.steer then return false end
		m = P.mount(m) or m
		return mr.eq(mr.read_pointer(m, 0x330), walk_b) and mr.read_uint8(m, 0x340) ~= 0
	end
	-- what he is doing, for the log: "walk" under our walk or the engine's, else "other" (a fight, a stand, a clip)
	function P.command(m)
		if not P.features.steer then return nil end
		local c = mr.read_pointer(m, 0x330)
		return (mr.eq(c, walk_a) or mr.eq(c, walk_b)) and "walk" or "other"
	end
	-- Holding still. Measured 2026-10-14 (probes/tp_cmd_trace.py): a walk that has reached its point, or was
	-- refreshed toward his own feet, keeps him moving until its command is replaced, and while F2 held him
	-- nothing replaced it. The cave has the engine's own stop swap a running walk, his or the regiment's, for "stand in
	-- his state" (what uc:halt leaves on each man); any other command is the engine's to finish.
	function P.hold(m, x, z, yaw)
		m = P.mount(m) or m
		for _, f in ipairs(STEER) do mr.write(m, f[1], x) mr.write(m, f[2], z) end
		if not P.features.steer then return end
		if block then post(m, "walk", 1) end
		P.face(m, yaw)
	end
	-- The engine's own orders on a man played alone, stopped by its own stop (measured 2026-10-16,
	-- probes/zz_tp_regiment_test.lua, Kossars in a lasting melee, nobody at the keys): the regiment's walk, two moves
	-- and the melee attack moved him 24.1 m in 30 s; stopped, 11 m, 8.5 m of it standing. The stop destroys any
	-- command, so the cave stops only those four (MB walk_a .. melee). Left to run: his idle (3919b28: stopped, a regiment
	-- charging past carried him 31.6 m standing against 4.9 m in it), knockbacks, knockdowns and the getting up, a dead man's
	function P.guard(m)
		m = P.mount(m) or m
		if not block then return false end
		post(m, "guard", 1)
		return true
	end
	-- No auto attack (measured 2026-10-16, probes/zz_tp_auto_attack.lua, the High Elves 30 s in a lasting melee, nobody
	-- at the keys): the stop above lands after the engine's melee has started its swing inside the battle's own tick, and
	-- the swing plays out - Tyrion swung 917 frames of 1195. On a copy of his fragment whose attack slots read none, the
	-- engine finds no swing to start on him: 0 (probes/zz_tp_mask_experiment.lua). His regiment keeps the shared one.
	-- Copies are kept for the battle in a global: a man may still point at one once this module is gone (a dead man)
	local keep = _G.DERPY_TP_FRAGS or {}
	_G.DERPY_TP_FRAGS = keep
	-- the copy of a fragment a with the given attack clips removed, deduped per (a, shots, charge). Multiplayer's copy
	-- table at "Deployed" calls this too, so a copy is byte-identical to what single player's point() makes
	local function build_copy(a, shots, charge)
		local key = mr.tostring(a) .. (shots and "+shots" or "") .. (charge and "+charge" or "")
		local c = copy_of[key]
		if not c then
			local blk = mr.alloc(FRAG_COPY)
			keep[#keep + 1] = blk
			c = mr.add(blk, 0) -- a plain pointer, written as the experiment wrote it
			for off = 0, FRAG_COPY - 8, 8 do mr.write(c, off, mr.read_pointer(a, off)) end
			for s = 454, 2116 do
				if is_attack(s) and not (charge and s >= 484 and s <= 493) or shots and is_shot(s) then
					mr.write(c, 0x50 + s * 2, mr.uint16(0xffff))
				end
			end
			copy_of[key], orig_of[mr.tostring(c)], shots_of[mr.tostring(c)] = c, a, shots
			charge_of[mr.tostring(c)] = charge
		end
		return c
	end
	local function point(x, shots, charge)
		shots = shots == true
		charge = charge == true
		local a = mr.read_pointer(x, FRAG)
		if mr.is_null(a) then return end
		local on = mr.tostring(a)
		if orig_of[on] then
			if shots_of[on] == shots and charge_of[on] == charge then return end
			a = orig_of[on] -- on the other kind's copy
		end
		mr.write(x, FRAG, build_copy(a, shots, charge))
	end
	-- the horse's swings and the rider's; shots: his shot clips too (one man of a regiment)
	function P.disarm(m, shots, charge)
		if not P.features.steer then return end
		local body = P.mount(m)
		if body then point(body, shots, charge) end
		point(m, shots, charge)
	end
	function P.arm(m)
		if not P.features.steer then return end
		local body = P.mount(m)
		if body then unpoint(body) end
		unpoint(m)
	end
	function P.same(a, b) return mr.eq(a, b) end
	function P.alive(unit, m)
		for _, x in ipairs(P.models(unit)) do if mr.eq(x, m) then return P.model_hp(m) > 0 end end
		return false
	end
	-- the live check (spec section 8), run at every start: the count matches the men alive, every model's
	-- type marker lies in the exe's image, their centre or one of them within 5 m of the unit's position (a deep
	-- block's centre is 5-6 m behind it, measured 2026-10-15; two men far apart have nobody at it), and
	-- the steering copies lie near their man or were never set. Measured 2026-10-13: a lord on a Longma is
	-- another model class than infantry (exe+3ac4908, not +390d4f8); a man never ordered holds 0, 0.
	local image_end = rva(base, pe + 0x50) -- SizeOfImage
	function P.check_men(unit)
		local obj = obj_of(unit)
		local n = mr.read_int32(obj, MODELS_N)
		if n < 1 or n ~= unit:number_of_men_alive() then return false, "model count " .. n .. " against " .. unit:number_of_men_alive() .. " men" end
		local ms = P.models(unit)
		local lo, hi = mr.tostring(base), mr.tostring(image_end)
		local q = unit:position()
		local qx, qz, near, sx, sz = q:get_x(), q:get_z(), 1e18, 0, 0
		for _, m in ipairs(ms) do
			-- one unit may hold two classes (measured 2026-10-14: an Ironbreaker regiment's two officers are
			-- exe+3ac5c40 beside its infantry's +390d4f8, with the same fields); each must still be one of the exe's
			local s = mr.tostring(mr.read_pointer(m, 0))
			if s < lo or s >= hi then return false, "a model type is not in the game's exe" end
			local x, _, z = P.model_pos(m)
			near, sx, sz = math.min(near, (x - qx) ^ 2 + (z - qz) ^ 2), sx + x, sz + z
			local body = P.mount(m) or m
			for _, f in ipairs(STEER) do
				local tx, tz = mr.read_float(body, f[1]), mr.read_float(body, f[2])
				if (tx ~= 0 or tz ~= 0) and (tx ~= tx or tz ~= tz or (tx - x) ^ 2 + (tz - z) ^ 2 > 90000) then return false, "a steering copy is not near its man" end
			end
		end
		local centre = (sx / n - qx) ^ 2 + (sz / n - qz) ^ 2
		if not (near <= 25 or centre <= 25) then
			return false, "the men centre " .. math.floor(math.sqrt(centre)) .. " m from the unit, the nearest " .. math.floor(math.sqrt(near)) .. " m"
		end
		P.features.men = true
		return true
	end

	-- multiplayer ---------------------------------------------------------------------------------------
	-- A lockstep battle runs only what its queue carries, and one direct write desyncs all of it within ticks
	-- (MP_FEASIBILITY_20261021_THIRD_PERSON.md, "Replay"). In one, steer, hold and face push the engine's own per-man
	-- overrides MOVE, HALT and FOLLOW_FIRST_PERSON, and the guard and the disarm the carrier on a RELOAD_TIME override, which
	-- no code reads ("O3"): forged as probes/zz_tp_mp_override.lua forged them live (record, "O4, pushing one"). P.play is
	-- the same command either way, with an ARM carrier ahead of a swing or shot. No steering copies, no +0xb0, no +0x308,
	-- no mailbox post
	P.net_delay = 0.2 -- s from a push to the engine running it: two ticks on one machine. PROVISIONAL until measured on two
	local function install_net()
		local types = {move = row.g_move, halt = row.g_halt, reload = row.g_reload}
		local g, ver = {}, {}
		for _, k in ipairs({"move", "halt", "reload"}) do -- each type's id is set at start-up by its registration
			g[k] = at(base, types[k])
			if zero32(g[k], 0) then return "the " .. k .. " command is not registered" end
			local e = mr.call(at(base, row.registry), "pointer(pointer)", g[k])
			if mr.is_null(e) then return "no registry entry for the " .. k .. " command" end
			ver[k] = mr.read_uint8(e, 0x10)
		end
		local header, field, length = at(base, row.rec_header), at(base, row.rec_field), at(base, row.rec_length)
		local follow_vt, follow_push = at(base, row.follow_vt), at(base, row.follow_push)
		local WR, REC, FC = mr.alloc(0x20), mr.alloc(64), mr.alloc(0x90)
		local function queue() -- P.play's queue and gate test
			local b = battle_obj()
			if not b or mr.read_uint8(b, A.gate_a) ~= 0 or mr.read_uint8(b, A.gate_b) ~= 0 then return nil end
			local q = mr.read_pointer(b, A.queue)
			if not mr.is_null(q) then return q end
		end
		-- the header, then the whole record in one field write (the first tag, then REC: the first value and every later
		-- tag and value raw), then its length, which also rewinds a record that overflowed the buffer
		local function push(k, tag, size)
			local q = queue()
			if not q then return false end
			mr.call(header, "pointer(pointer, pointer, pointer, uint8)", WR, mr.add(q, 8), g[k], ver[k])
			mr.call(field, "int32(pointer, uint8, pointer, int32)", WR, tag, REC, size)
			local err = mr.read_uint8(WR, 0) -- the writer's error flags: the record overflowed the buffer, and is rewound
			mr.call(length, "int32(pointer)", WR)
			return err == 0
		end
		local function man_id(b) mr.write(REC, 0, mr.uint16(u16(b, 0x258))) mr.write(REC, 2, mr.uint16(u16(b, 0x25a))) end
		local out = {}
		-- 0x23 man; 0x0c x y z; 0x26 0; 0x27 0; 0x04 run; 0x0a speed. He faces his path: MOVE carries no heading
		function out.move(b, x, z, run, _, scale)
			local unit = mr.read_pointer(b, 0x2e8)
			if mr.is_null(unit) then return false end
			local speed = mr.call(walk_speed, "float(pointer, uint8)", unit, run and 1 or 0) * (scale or 1)
			man_id(b)
			mr.write(REC, 4, mr.uint8(0x0c)) mr.write(REC, 5, x) mr.write(REC, 9, bm:get_terrain_height(x, z)) mr.write(REC, 13, z)
			mr.write(REC, 17, mr.uint8(0x26)) mr.write(REC, 18, mr.uint32(0))
			mr.write(REC, 22, mr.uint8(0x27)) mr.write(REC, 23, mr.uint32(0))
			mr.write(REC, 27, mr.uint8(4)) mr.write(REC, 28, mr.uint32(run and 1 or 0))
			mr.write(REC, 32, mr.uint8(0x0a)) mr.write(REC, 33, speed)
			return push("move", 0x23, 37)
		end
		function out.halt(b) man_id(b) return push("halt", 0x23, 4) end
		-- CA's own command (vtable, pusher): the 0x90 bytes its builder makes, heading in his +0xb0's unit
		function out.follow(b, yaw)
			local q = queue()
			if not q then return false end
			for o = 0, 0x8c, 4 do mr.write(FC, o, mr.uint32(0)) end
			mr.write(FC, 0, follow_vt)
			mr.write(FC, 8, b)
			mr.write(FC, 0x30, mr.uint16(heading16(yaw)))
			mr.write(FC, 0x78, mr.int32(-1)) -- no weapon
			mr.write(FC, 0x80, mr.uint32(0x81)) -- CA's stand state
			mr.write(FC, 0x88, 1.0)
			mr.call(follow_push, "uint8(pointer, pointer)", q, FC)
			return true
		end
		-- the word as two u16s, low half first: a u32 above 2^24 is no exact Lua number. A man whose id does not fit 16
		-- bits is refused by M.carrier and gets nothing, never another man's id. id: one sent before (GUARD_OFF), and b is
		-- not read; returns whether it went, and the id
		function out.carrier(b, op, flags, id)
			id = id or u16(b, 0x25a) * 0x10000 + u16(b, 0x258)
			local ok, hi, lo = pcall(M.carrier, op, id, flags)
			if not ok then
				if once then once("carrier_id", "a man is left out of multiplayer guarding: " .. tostring(hi)) end
				return false
			end
			mr.write(REC, 0, mr.uint16(lo))
			mr.write(REC, 2, mr.uint16(hi))
			return push("reload", 0x0a, 4), id
		end
		out.play = P.play -- single player's push; in net mode it leaves +0x308 to the carrier
		-- the carrier cave at exe+2ecfcb7 decodes the carrier on every machine, on the command executor's thread, and
		-- applies the guard, disarm and arm. It shares the mailbox block (so the update cave's guard table and the copy
		-- table are the same memory), so the mailbox must be in. It goes in before any single-player function is swapped
		-- out, so a refusal leaves single player standing; and its two pointers go in before it does, since a carrier
		-- reaching a cave whose skip is still 0 would jump to 0
		if not block then return "the carrier cave needs the mailbox block, which did not install" end
		if mr.read_original(at(base, row.reload_hook), 0, #CARRIER_SITE) ~= string.char(unpack(CARRIER_SITE)) then
			return "the RELOAD_TIME float read is not the code the carrier cave expects"
		end
		mr.write(block, MB.skip, mr.add(at(base, row.reload_resume), 8)) -- a carrier skips the global's store (exe+2ecfcc5)
		mr.write(block, MB.map_lookup, at(base, row.map_lookup))
		local cbytes, chex = {unpack(CARRIER)}, mr.tostring(block)
		for i = 0, 7 do cbytes[CARRIER_BLOCK + i + 1] = tonumber(chex:sub(15 - 2 * i, 16 - 2 * i), 16) end -- low byte first
		local ccave, cwhy = mr.patcher("derpy_tp"):cave("carrier", at(base, row.reload_hook), string.char(unpack(cbytes)))
		if not ccave then return "the carrier cave: " .. tostring(cwhy) end
		-- the order gate changes the simulation, so a machine with it out, or one that set it at a key press, resets a melee
		-- MOVE the others run (measured live, the record's "The overrides, live") and desyncs in the first melee. Every
		-- machine puts it in at the handshake's completion (M.handshake, the record's Ruling 25; one tick everywhere is
		-- inferred, BATTLE_ENGINE_RE.md section 14), and nothing takes it out before the battle ends (main.lua leaves it alone in net mode). Here its code is checked, and its write proven by
		-- putting it in and out again: a machine that could not write it at the handshake would leave the others to start
		-- with their gate in and its own out, so it is no net mode and never says HELLO. The build runs as the battle loads,
		-- before its first tick, so the gate in for these two writes changes no man's update. The build took out a gate a
		-- battle before left in. Last of the refusals, so one still leaves single player standing
		if not gate_out() then return "the order gate's code is not the code it expects" end
		if not P.gate(true) then return "the order gate cannot be written" end
		if not P.gate(false) then return "the order gate went in and cannot be taken out" end
		local R = M.net_rules(P, out, function(b) return mr.tostring(b) end)
		P.steer, P.hold, P.face, P.guard, P.unguard, P.disarm, P.arm = R.steer, R.hold, R.face, R.guard, R.unguard, R.disarm, R.arm
		P.net_reset, P.play, P.watch = R.reset, R.play, R.watch

		-- every army's units across all alliances, in the battle's own order; a flat list. Every army, not the human ones:
		-- what is_player_controlled means on each machine is unmeasured, and a fragment missing on one desyncs
		-- (the record's Ruling 16)
		local function all_units()
			local t, alliances = {}, bm:alliances()
			for i = 1, alliances:count() do
				local armies = alliances:item(i):armies()
				for j = 1, armies:count() do
					local units = armies:item(j):units()
					for k = 1, units:count() do t[#t + 1] = units:item(k) end
				end
			end
			return t
		end
		-- a unit's men, or none when it cannot be read (no object yet, a reinforcement army off the field; a read that
		-- faults, which memreader turns into a Lua error): that unit is left out, not the table. The battle's own state,
		-- so the same on every machine
		local function men_of(unit)
			local ok, men = pcall(function() return not mr.is_null(obj_of(unit)) and P.models(unit) or {} end)
			return ok and men or {}
		end
		-- the fragment copy table, built fresh at "Deployed" on every machine: for every fragment of every army's men and
		-- their mounts, deduped by address, {orig, plain, shots, charge, shots_charge}. ipairs only and no random, so the
		-- content is identical on every machine (only the addresses differ). The guard table is not touched: the build
		-- zeroed it (check_mailbox), and a clear here runs beside the battle's threads (the record's Ruling 20). A
		-- later-spawned unit (a summon, a reinforcement) is not in the table, so a DISARM naming its fragment is dropped
		local function build_copy_table()
			if not block then return end
			local seen, rows = {}, {}
			for _, unit in ipairs(all_units()) do
				for _, m in ipairs(men_of(unit)) do
					-- each man's fragment, then his mount's: DISARM names the horse's too (P.disarm points both)
					for _, x in ipairs({m, P.mount(m) or false}) do
						local a = x and mr.read_pointer(x, FRAG)
						if a and not mr.is_null(a) and not seen[mr.tostring(a)] then
							seen[mr.tostring(a)] = true
							rows[#rows + 1] = {a, build_copy(a, false, false), build_copy(a, true, false),
								build_copy(a, false, true), build_copy(a, true, true)}
						end
					end
				end
			end
			if #rows > 0 then
				local tab = mr.game_alloc(#rows * 0x28)
				for i, r in ipairs(rows) do for j = 1, 5 do mr.write(tab, (i - 1) * 0x28 + (j - 1) * 8, r[j]) end end
				mr.write(block, MB.fragtab, tab)
			end
			mr.write(block, MB.nfrags, mr.uint32(#rows))
			return #rows
		end
		-- this machine's HELLO waits for it (P.net_ready, M.handshake): a machine with no table drops every DISARM, so no
		-- peer starts before every table is built. One that throws leaves net play off for the battle, said once. How long
		-- it took is said too, in model and real time (the model clock reads 0 if the battle waits for the build)
		bm:register_phase_change_callback("Deployed", function()
			local t, c = bm:time_elapsed_ms(), os.clock()
			local ok, res = pcall(build_copy_table)
			if ok then P.net_ready = true end
			if not once then return end
			local real = math.floor((os.clock() - c) * 1000 + 0.5)
			once("copy_table_ms", "the fragment table took " .. tostring(bm:time_elapsed_ms() - t) .. " model ms ("
				.. tostring(real) .. " real ms)" .. (ok and ", " .. tostring(res) .. " fragments" or ""))
			if not ok then once("copy_table", "multiplayer is off for this battle: the fragment table did not build: " .. tostring(res)) end
		end)
		P.build_copy_table = build_copy_table -- the harness fires it to check the table
		-- the HELLO handshake, a model callback (it runs at the same model times on every machine; where in the tick is
		-- untraced): player slot n's HELLO is bit n of the block's mask, which the carrier cave sets and the build zeroed
		local function heard(slot)
			local b = mr.read_uint8(block, MB.hello + math.floor(slot / 8))
			for _ = 1, slot % 8 do b = math.floor(b / 2) end
			return b % 2 == 1
		end
		bm:remove_callback("derpy_tp_hello")
		bm:repeat_callback(M.handshake(P, function(slot) return (out.carrier(nil, "HELLO", nil, slot)) end, heard, once,
			M.players), 100, "derpy_tp_hello")
	end
	-- single player: the guard is a request posted each frame, and nothing is kept between sessions. Net mode only:
	-- P.net_ready, this machine's copy table is built (set at "Deployed"); P.net_asked, this player pressed F2 (main.lua),
	-- so this machine says HELLO; P.net_late, the handshake has waited HELLO_WAIT (P.net_why: why); P.net_play, every
	-- player said HELLO and the gate is in (M.handshake), and play may start; P.net_me, this machine's player
	function P.unguard() end
