	-- a throw here is no net mode, never a lost load: the entry's guard still tells a multiplayer player
	if net then
		local why = not (A and P.build == "6acec6f4" and P.features.steer) and "no multiplayer route on build " .. P.build
		if not why then
			local ok, res = pcall(install_net)
			why = not ok and "multiplayer route: " .. tostring(res) or res
		end
		if why then
			problem("net", why)
			-- no gate: nothing at build leaves it in but a proof whose out-write failed, which the reason says (a refused
			-- machine never says HELLO, so no peer puts it in either). The
			-- carrier cave, if it went in, stays: memreader Plus cannot remove a cave for the session (BATTLE_ENGINE_RE.md
			-- section 9). It still claims a net-mode peer's guard entries and stops that man's orders here only, so this
			-- machine desyncs against such a peer; with no peer in net mode it does nothing
		else
			P.features.net = true
		end
	end

	return P
end

