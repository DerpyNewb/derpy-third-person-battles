"""Mirror Third-Person Battles into repos/derpy-third-person-battles, the public repo.

The workspace is the source of truth; the repo is a copy with the same layout, so every
tool's relative paths ("Modding Files/...", "tools/...") work from either root.
README.md, CHANGELOG.md, LICENSE, .gitignore and .gitattributes are written in the repo
itself and never touched here. The copying is sync_guilds_repo's.

    py tools/sync_third_person_repo.py            # copy every changed file into the repo
    py tools/sync_third_person_repo.py --check    # list drift, copy nothing; exit 1 on drift
    py tools/sync_third_person_repo.py --selftest

Then commit and push from inside the repo folder.

The mod's source (Modding Files/source/third_person - the pack is built from it, so it is the truth,
unlike the lords pack's staged Lua), every tool that builds, tests, previews or checks it plus
their import closure, the live-game probes and the mutation sets, the design record, and the exe
reverse-engineering tools with their write-up (docs/BATTLE_ENGINE_RE.md). The
rejected first attempt (lord_control) comes along because the probes live under it.

NOTHING OF CA'S OR GW'S IS PUBLISHED, no file naming a Windows user profile, and no decompiled exe code
(a ```c block; that lives in docs/BATTLE_ENGINE_RE_DECOMPILED.md, local only). data.lua is
generated from db.pack but holds keys and numbers only (unit -> projectile, reload, count, sound
event; ability -> target kind), which the harness needs. hud.twui.xml is OURS - written by
gen_third_person_hud.py, it only names CA's art paths - and is the one .twui.xml let through.
`refused()` checks every manifest entry, by extension and by content, and the sync will not run
while it reports anything.
"""
