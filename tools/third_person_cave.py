"""The third-person pack's mailbox: a code cave at the top of a man's update (exe+3086f04 on 6acec6f4) that stops,
starts and steers the man played alone ON THE BATTLE THREAD, from requests the script thread posts into a block.

    py tools/third_person_cave.py              write the cave's bytes and the block's offsets into platform.lua
    py tools/third_person_cave.py --check      exit 1 when platform.lua's bytes are not this file's assembly, or the
                                               site in the exe on disk is not the code the cave displaces
    py tools/third_person_cave.py --selftest   run the bytes platform.lua SHIPS under an x64 emulator (unicorn), then
                                               break the assembly eight ways and prove each break is caught

Why: the battle runs on worker threads while the script runs (docs/BATTLE_ENGINE_RE.md section 9). P.guard, P.hold and
P.steer called the engine's stop (exe+306edd4) and its walk builder (exe+306f954) from the script thread; both destroy
the command at +0x328/+0x330 that a worker may be running. Crashes exe+0x305B39A (2026-10-16) and exe+0x7AB1DA
(2026-10-17, reading FFFFFFFFFFFFFFFF in a command's destructor, the script log's last line P.guard). The cave makes the
same calls, with the same tests, from the start of his own update, where the engine itself changes his command.

The block (game_alloc, 0x100 bytes, kept for the session: the cave holds its address, and a later battle reads it back
from the cave's first instruction, mov rax, <block>):

    man        the model the requests are for (the mount of a rider); 0 nobody
    walk_a .. walk_start   the four engine commands the guard stops, his own walk, the stop and the walk builder
    guard      1: stop his command if it is one of the engine's four (exchanged with 0 as it is read)
    walk       1 hold: stop a walk; 2 steer: update his own walk in place, else build one from buf (unless near)
    stops, met counters: the guard's stops, and the updates the cave matched him in (for probes)
    has_angle  steer: write buf's angle in place; near: steer: he is at the point, build no walk
    buf        the walk builder's 0x60-byte parameter block (platform.lua fills it as it always did)

Needs keystone-engine (assembling) and unicorn (the selftest), both pip packages; capstone for the comments.
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PLATFORM = os.path.join(HERE, "..", "Modding Files", "source", "third_person", "script", "derpy_tp", "platform.lua")
BEGIN, END = "-- cave: generated by tools/third_person_cave.py", "-- end of the cave"
SITE_RVA = 0x3086f04  # a man's update on 6acec6f4 (vtable +0x18; every model class reaches it, docs section 4)
SITE_BYTES = bytes.fromhex("488bc4 48895810")  # mov rax, rsp; mov [rax+0x10], rbx: what the cave's jump displaces
PLACEHOLDER = 0x1122334455667788

MB = {"man": 0x00, "walk_a": 0x08, "move_a": 0x10, "move_b": 0x18, "melee": 0x20, "walk_b": 0x28, "walk_stop": 0x30,
      "walk_start": 0x38, "guard": 0x40, "walk": 0x44, "stops": 0x48, "met": 0x4c, "has_angle": 0x50, "near": 0x51,
      "buf": 0x80, "size": 0x100}
# the walk builder's parameter block (platform.lua) and the man's fields the in-place steer writes (docs section 3)
BUF = {"x": 0x0, "z": 0x8, "run": 0x28, "speed": 0x2c, "angle": 0x30, "gait": 0x46}
MAN = {"cmd": 0x330, "hp": 0xb1c, "x": 0x368, "z": 0x370, "run": 0x390, "speed": 0x394, "angle": 0x398,
       "gait": 0x3ae, "fresh": 0x3c0}

# At the site: a virtual call's entry, so the standard ABI - rsp is 8 past a 16-byte boundary, rcx/rdx/r8/r9 and
# xmm0-3 may hold arguments, rax and the flags are dead (the next instruction is mov rax, rsp). Anything else the cave
# touches it gives back. Every call is made with rsp on a 16-byte boundary and 32 bytes of shadow space.
ASM = """
    mov rax, {placeholder}
    cmp rcx, qword ptr [rax + {man}]
    jne done
    push rbx
    push rsi
    push rcx
    push rdx
    push r8
    push r9
    sub rsp, 0x68
    movdqu xmmword ptr [rsp + 0x20], xmm0
    movdqu xmmword ptr [rsp + 0x30], xmm1
    movdqu xmmword ptr [rsp + 0x40], xmm2
    movdqu xmmword ptr [rsp + 0x50], xmm3
    mov rbx, rax
    mov rsi, rcx
    inc dword ptr [rbx + {met}]
    cmp dword ptr [rsi + {m_hp}], 0
    jg alive
    mov dword ptr [rbx + {guard}], 0
    mov dword ptr [rbx + {walk}], 0
    jmp restore
alive:
    xor eax, eax
    xchg dword ptr [rbx + {guard}], eax
    test eax, eax
    je walk
    mov rax, qword ptr [rsi + {m_cmd}]
    cmp rax, qword ptr [rbx + {walk_a}]
    je engine
    cmp rax, qword ptr [rbx + {move_a}]
    je engine
    cmp rax, qword ptr [rbx + {move_b}]
    je engine
    cmp rax, qword ptr [rbx + {melee}]
    jne walk
engine:
    mov rcx, rsi
    call qword ptr [rbx + {walk_stop}]
    inc dword ptr [rbx + {stops}]
walk:
    xor eax, eax
    xchg dword ptr [rbx + {walk}], eax
    cmp eax, 1
    je hold
    cmp eax, 2
    jne restore
    mov rax, qword ptr [rsi + {m_cmd}]
    cmp rax, qword ptr [rbx + {walk_b}]
    je in_place
    cmp byte ptr [rbx + {near}], 0
    jne restore
    mov rcx, rsi
    lea rdx, [rbx + {buf}]
    call qword ptr [rbx + {walk_start}]
    jmp restore
in_place:
    xor r8d, r8d
    mov eax, dword ptr [rbx + {b_x}]
    mov edx, eax
    xor edx, dword ptr [rsi + {m_x}]
    or r8d, edx
    mov dword ptr [rsi + {m_x}], eax
    mov eax, dword ptr [rbx + {b_z}]
    mov edx, eax
    xor edx, dword ptr [rsi + {m_z}]
    or r8d, edx
    mov dword ptr [rsi + {m_z}], eax
    mov eax, dword ptr [rbx + {b_run}]
    mov dword ptr [rsi + {m_run}], eax
    mov eax, dword ptr [rbx + {b_speed}]
    mov dword ptr [rsi + {m_speed}], eax
    movzx eax, byte ptr [rbx + {b_gait}]
    movzx edx, byte ptr [rsi + {m_gait}]
    xor edx, eax
    or r8d, edx
    mov byte ptr [rsi + {m_gait}], al
    cmp byte ptr [rbx + {has_angle}], 0
    je placed
    movzx eax, word ptr [rbx + {b_angle}]
    movzx edx, word ptr [rsi + {m_angle}]
    xor edx, eax
    or r8d, edx
    mov word ptr [rsi + {m_angle}], ax
placed:
    test r8d, r8d
    je restore
    mov byte ptr [rsi + {m_fresh}], 0
    jmp restore
hold:
    mov rax, qword ptr [rsi + {m_cmd}]
    cmp rax, qword ptr [rbx + {walk_a}]
    je stop
    cmp rax, qword ptr [rbx + {walk_b}]
    jne restore
stop:
    mov rcx, rsi
    call qword ptr [rbx + {walk_stop}]
restore:
    movdqu xmm0, xmmword ptr [rsp + 0x20]
    movdqu xmm1, xmmword ptr [rsp + 0x30]
    movdqu xmm2, xmmword ptr [rsp + 0x40]
    movdqu xmm3, xmmword ptr [rsp + 0x50]
    add rsp, 0x68
    pop r9
    pop r8
    pop rdx
    pop rcx
    pop rsi
    pop rbx
done:
"""


def fields():
    f = {k: hex(v) for k, v in MB.items()}
    f.update({"b_" + k: hex(MB["buf"] + v) for k, v in BUF.items()})
    f.update({"m_" + k: hex(v) for k, v in MAN.items()})
    f["placeholder"] = hex(PLACEHOLDER)
    return f


def assemble(asm=ASM):
    """(bytes with the block placeholder zeroed, offset of the block's 8 bytes)."""
    import keystone
    ks = keystone.Ks(keystone.KS_ARCH_X86, keystone.KS_MODE_64)
    code, _ = ks.asm(asm.format(**fields()), 0)
    code = bytes(code)
    mark = struct.pack("<Q", PLACEHOLDER)
    at = code.find(mark)
    assert at >= 0 and code.find(mark, at + 1) < 0, "the block placeholder once"
    return code[:at] + bytes(8) + code[at + 8:], at


def lua_text(code, at):
    import capstone
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    lines = [BEGIN + " from its assembly (--check, --selftest)",
             "-- the block's offsets (platform.lua writes them, the cave reads them) and the cave's bytes, its block at CAVE_BLOCK",
             "local MB = {" + ", ".join("%s = 0x%x" % (k, MB[k]) for k in MB) + "}",
             "local CAVE_BLOCK = %d" % at,
             "local CAVE_SITE = {" + ", ".join("0x%02x" % b for b in SITE_BYTES) + "} -- the bytes its jump displaces",
             "local CAVE = {"]
    for ins in md.disasm(code, 0):
        text = "%s %s" % (ins.mnemonic, ins.op_str)
        if ins.address == at - 2:
            text = "mov rax, <block>"
        lines.append("\t" + ", ".join("0x%02x" % b for b in ins.bytes) + ", -- %s" % text.strip())
    lines += ["}", END]
    return "\n".join(lines)


def shipped():
    """(bytes, block offset, MB) parsed out of platform.lua: what the pack actually carries."""
    s = open(PLATFORM, encoding="utf-8", newline="").read()
    i, j = s.find(BEGIN), s.find(END)
    if i < 0 or j < 0:
        raise SystemExit("platform.lua carries no cave (markers %r .. %r)" % (BEGIN, END))
    region = s[i:j]
    table = region[region.find("local CAVE = {"):]
    code = bytes(int(h, 16) for h in re.findall(r"0x([0-9a-f]{2}),", re.sub(r"--[^\n]*", "", table)))
    at = int(re.search(r"local CAVE_BLOCK = (\d+)", region).group(1))
    mb = {k: int(v, 16) for k, v in re.findall(r"(\w+) = 0x([0-9a-f]+)", re.search(r"local MB = \{([^}]*)\}", region).group(1))}
    return code, at, mb


def write():
    code, at = assemble()
    text = lua_text(code, at)
    s = open(PLATFORM, encoding="utf-8", newline="").read()
    nl = "\r\n" if "\r\n" in s else "\n"
    text = text.replace("\n", nl)
    i, j = s.find(BEGIN), s.find(END)
    if i < 0 or j < 0:
        raise SystemExit("put the two marker lines into platform.lua first: %r and %r" % (BEGIN, END))
    s = s[:i] + text + s[j + len(END):]
    open(PLATFORM, "w", encoding="utf-8", newline="").write(s)
    print("wrote %d cave bytes, block at +%d, into %s" % (len(code), at, PLATFORM))


def check():
    sys.path.insert(0, HERE)
    import exe_re
    code, at = assemble()
    got, gat, mb = shipped()
    bad = []
    if (got, gat) != (code, at):
        bad.append("platform.lua's cave is not this file's assembly: run py tools/third_person_cave.py")
    if mb != MB:
        bad.append("platform.lua's block offsets differ: %r" % mb)
    exe_re.pe()
    on_disk = exe_re._pe[exe_re.off(SITE_RVA):exe_re.off(SITE_RVA) + len(SITE_BYTES)]
    if on_disk != SITE_BYTES:
        bad.append("exe+%x reads %s, not %s: a patch moved his update" % (SITE_RVA, on_disk.hex(" "), SITE_BYTES.hex(" ")))
    for b in bad:
        print("FAIL " + b)
    if not bad:
        print("ok: %d bytes, block at +%d, site exe+%x as expected" % (len(code), at, SITE_RVA))
    return not bad


# -- the emulator ----------------------------------------------------------------------------------------------------
CODE, STUBS, BLOCK, HIM, OTHER, STACK = 0x10000000, 0x20000000, 0x30000000, 0x40000000, 0x41000000, 0x50000000
STOP, START = STUBS, STUBS + 0x100
VT = {"walk_a": 0x143919350, "move_a": 0x1439199f8, "move_b": 0x143ae1928, "melee": 0x143ad24b8,
      "walk_b": 0x143ae2400, "clip": 0x143911fb0, "stand": 0x1439126f0, "idle": 0x143919b28, "fight": 0x143ae2b38,
      "fight2": 0x143ae2a08, "fight3": 0x143912820}
KEEP = ["rcx", "rdx", "r8", "r9", "rbx", "rsi", "rdi", "rbp", "r12", "r13", "r14", "r15", "rsp"]
# a callee may wreck every volatile register: the stubs do, so a cave that leans on one is caught
WRECK = ("mov rcx, -1; mov rdx, -2; mov r8, -3; mov r9, -4; mov r10, -5; mov r11, -6; mov rax, -7; "
         "pcmpeqd xmm0, xmm0; pcmpeqd xmm1, xmm1; pcmpeqd xmm2, xmm2; pcmpeqd xmm3, xmm3; pcmpeqd xmm4, xmm4; "
         "pcmpeqd xmm5, xmm5; ret")


def run(code, at, setup, rcx=HIM):
    """Run the cave once as his update's entry would; returns (calls, regs before, regs after, mem read)."""
    import keystone
    import unicorn
    from unicorn import x86_const as X
    uc = unicorn.Uc(unicorn.UC_ARCH_X86, unicorn.UC_MODE_64)
    for base in (CODE, STUBS, BLOCK, HIM, OTHER, STACK):
        uc.mem_map(base, 0x10000)
    ks = keystone.Ks(keystone.KS_ARCH_X86, keystone.KS_MODE_64)
    stub = bytes(ks.asm(WRECK, 0)[0])
    uc.mem_write(STOP, stub)
    uc.mem_write(START, stub)
    code = code[:at] + struct.pack("<Q", BLOCK) + code[at + 8:]
    uc.mem_write(CODE, code)

    def q(addr, v): uc.mem_write(addr, struct.pack("<Q", v))
    def d(addr, v): uc.mem_write(addr, struct.pack("<I", v))
    for k in ("walk_a", "move_a", "move_b", "melee", "walk_b"):
        q(BLOCK + MB[k], VT[k])
    q(BLOCK + MB["walk_stop"], STOP)
    q(BLOCK + MB["walk_start"], START)
    q(BLOCK + MB["man"], HIM)
    d(HIM + MAN["hp"], 80)
    setup(q, d, uc)

    regs = {r: getattr(X, "UC_X86_REG_" + r.upper()) for r in KEEP}
    before = {}
    for n, r in enumerate(KEEP):
        if r == "rsp":
            continue
        v = 0x7700000000 + n * 0x1111
        uc.reg_write(regs[r], v)
        before[r] = v
    uc.reg_write(regs["rcx"], rcx)
    before["rcx"] = rcx
    sp = STACK + 0x8000 - 8  # a function's entry: its return address just pushed
    uc.reg_write(regs["rsp"], sp)
    before["rsp"] = sp
    xmm = {i: getattr(X, "UC_X86_REG_XMM%d" % i) for i in range(4)}
    for i in range(4):
        uc.reg_write(xmm[i], 0x0123456789abcdef0011223344556677 + i)
    calls = []

    def hook(u, addr, size, _):
        if addr in (STOP, START):
            calls.append(("stop" if addr == STOP else "start", u.reg_read(regs["rcx"]), u.reg_read(regs["rdx"]),
                          u.reg_read(regs["rsp"]) % 16))
    uc.hook_add(unicorn.UC_HOOK_CODE, hook, begin=STUBS, end=STUBS + 0x1000)
    uc.emu_start(CODE, CODE + len(code), count=10000)
    after = {r: uc.reg_read(regs[r]) for r in KEEP}
    ok_xmm = all(uc.reg_read(xmm[i]) == 0x0123456789abcdef0011223344556677 + i for i in range(4))
    rip = uc.reg_read(X.UC_X86_REG_RIP)

    def rd(addr, n): return int.from_bytes(uc.mem_read(addr, n), "little")
    return {"calls": calls, "before": before, "after": after, "xmm": ok_xmm, "end": rip == CODE + len(code), "rd": rd}


def scenarios(code, at):
    """Every case the cave has to get right. Returns the failures as text."""
    fails = []

    def expect(cond, what):
        if not cond:
            fails.append(what)

    def kept(r, what):
        expect(r["end"], what + ": falls through to the displaced instructions")
        expect(r["xmm"], what + ": xmm0-3 kept")
        for k in KEEP:
            expect(r["after"][k] == r["before"][k], "%s: %s kept (%x -> %x)" % (what, k, r["before"][k], r["after"][k]))
        for c in r["calls"]:
            expect(c[3] == 8, what + ": a call's callee sees rsp 8 past a 16-byte boundary")

    def cmd(vt, guard=0, walk=0, hp=80, near=0, has_angle=0):
        def setup(q, d, uc):
            q(HIM + MAN["cmd"], VT[vt])
            d(HIM + MAN["hp"], hp)
            d(BLOCK + MB["guard"], guard)
            d(BLOCK + MB["walk"], walk)
            uc.mem_write(BLOCK + MB["near"], bytes([near]))
            uc.mem_write(BLOCK + MB["has_angle"], bytes([has_angle]))
        return setup

    # somebody else's update: nothing, not even a counter
    r = run(code, at, cmd("melee", guard=1, walk=2), rcx=OTHER)
    kept(r, "another man")
    expect(not r["calls"] and r["rd"](BLOCK + MB["guard"], 4) == 1 and r["rd"](BLOCK + MB["met"], 4) == 0,
           "another man: no call, his requests wait for him")
    # nobody played (man 0) and a null this never match
    r = run(code, at, lambda q, d, uc: (cmd("melee", guard=1)(q, d, uc), q(BLOCK + MB["man"], 0)), rcx=OTHER)
    expect(not r["calls"], "nobody played: no call")
    # the guard: the engine's four are stopped, everything else runs
    for vt in ("walk_a", "move_a", "move_b", "melee"):
        r = run(code, at, cmd(vt, guard=1))
        kept(r, "guard " + vt)
        expect([c[:2] for c in r["calls"]] == [("stop", HIM)], "guard: %s stopped on him, got %r" % (vt, r["calls"]))
        expect(r["rd"](BLOCK + MB["stops"], 4) == 1 and r["rd"](BLOCK + MB["guard"], 4) == 0, "guard %s: counted, request taken" % vt)
        expect(r["rd"](BLOCK + MB["met"], 4) == 1, "guard %s: met once" % vt)
    for vt in ("walk_b", "clip", "stand", "idle", "fight", "fight2", "fight3"):
        r = run(code, at, cmd(vt, guard=1))
        kept(r, "guard " + vt)
        expect(not r["calls"] and r["rd"](BLOCK + MB["guard"], 4) == 0, "guard: %s left to run, request taken" % vt)
    r = run(code, at, cmd("melee"))
    expect(not r["calls"], "no guard request: the engine's melee runs")
    # a dead man: nothing, and his requests go
    r = run(code, at, cmd("melee", guard=1, walk=2, hp=0))
    kept(r, "dead")
    expect(not r["calls"] and r["rd"](BLOCK + MB["guard"], 4) == 0 and r["rd"](BLOCK + MB["walk"], 4) == 0,
           "a dead man: no call, requests dropped")
    # hold: a walk, his or the regiment's, stopped; anything else the engine's
    for vt, stopped in (("walk_a", True), ("walk_b", True), ("melee", False), ("clip", False), ("stand", False)):
        r = run(code, at, cmd(vt, walk=1))
        kept(r, "hold " + vt)
        expect([c[:2] for c in r["calls"]] == ([("stop", HIM)] if stopped else []), "hold %s: %r" % (vt, r["calls"]))
        expect(r["rd"](BLOCK + MB["walk"], 4) == 0, "hold %s: request taken" % vt)
    # steer, not walking his own: a new walk from the buffer, unless he is at the point
    for vt in ("walk_a", "melee", "stand", "clip"):
        r = run(code, at, cmd(vt, walk=2))
        kept(r, "steer " + vt)
        expect([c[:3] for c in r["calls"]] == [("start", HIM, BLOCK + MB["buf"])], "steer %s: walk built, %r" % (vt, r["calls"]))
    r = run(code, at, cmd("stand", walk=2, near=1))
    expect(not r["calls"] and r["rd"](BLOCK + MB["walk"], 4) == 0, "steer at the point: no walk, request taken")
    # steer under his own walk: written in place; the fresh byte cleared only when something changed
    def own(same, angle_differs=False, has_angle=1, gait_differs=False):
        def setup(q, d, uc):
            cmd("walk_b", walk=2, has_angle=has_angle)(q, d, uc)
            for k, v in (("x", 0x41200000), ("z", 0xC1A00000), ("run", 1), ("speed", 0x40800000)):
                d(BLOCK + MB["buf"] + BUF[k], v)
            uc.mem_write(BLOCK + MB["buf"] + BUF["gait"], bytes([1]))
            uc.mem_write(BLOCK + MB["buf"] + BUF["angle"], struct.pack("<H", 0x4000))
            d(HIM + MAN["x"], 0x41200000 if same else 0x41100000)
            d(HIM + MAN["z"], 0xC1A00000)
            uc.mem_write(HIM + MAN["gait"], bytes([0 if gait_differs else 1]))
            uc.mem_write(HIM + MAN["angle"], struct.pack("<H", 0x3000 if angle_differs else 0x4000))
            uc.mem_write(HIM + MAN["fresh"], bytes([7]))
        return setup
    for name, kw, fresh in (("moved", dict(same=False), 0), ("same", dict(same=True), 7),
                            ("turned", dict(same=True, angle_differs=True), 0), ("gait", dict(same=True, gait_differs=True), 0),
                            ("turned, no angle given", dict(same=True, angle_differs=True, has_angle=0), 7)):
        r = run(code, at, own(**kw))
        kept(r, "in place " + name)
        expect(not r["calls"], "in place %s: no call" % name)
        rd = r["rd"]
        expect(rd(HIM + MAN["x"], 4) == 0x41200000 and rd(HIM + MAN["z"], 4) == 0xC1A00000, "in place %s: x, z" % name)
        expect(rd(HIM + MAN["run"], 4) == 1 and rd(HIM + MAN["speed"], 4) == 0x40800000 and rd(HIM + MAN["gait"], 1) == 1,
               "in place %s: run, speed, gait" % name)
        want_angle = 0x4000 if kw.get("has_angle", 1) else (0x3000 if kw.get("angle_differs") else 0x4000)
        expect(rd(HIM + MAN["angle"], 2) == want_angle, "in place %s: angle %x" % (name, rd(HIM + MAN["angle"], 2)))
        expect(rd(HIM + MAN["fresh"], 1) == fresh, "in place %s: fresh byte %d, want %d" % (name, rd(HIM + MAN["fresh"], 1), fresh))
    # both requests in one update: the guard first, then the walk
    r = run(code, at, cmd("melee", guard=1, walk=2))
    expect([c[0] for c in r["calls"]] == ["stop", "start"], "guard then steer: %r" % r["calls"])
    return fails


# plausible mistakes; each must be caught by scenarios()
MUTANTS = [
    ("xmm1 not kept", "    movdqu xmm1, xmmword ptr [rsp + 0x30]\n", ""),
    ("rdx not kept", "    pop rdx\n", "    pop rax\n"),
    ("misaligned calls", "    sub rsp, 0x68\n", "    sub rsp, 0x60\n"),
    ("the melee command not stopped", "    cmp rax, qword ptr [rbx + {melee}]\n    jne walk\n", "    jmp walk\n"),
    ("the guard request never taken", "    xchg dword ptr [rbx + {guard}], eax\n", "    mov eax, dword ptr [rbx + {guard}]\n"),
    ("his own walk rebuilt every tick", "    je in_place\n", "    nop\n"),
    ("a dead man stopped", "    jg alive\n", "    jmp alive\n"),
    ("fresh cleared on every steer", "    test r8d, r8d\n    je restore\n", ""),
]


def selftest():
    code, at, mb = shipped()
    if mb != MB:
        print("FAIL platform.lua's block offsets differ from this file's")
        return False
    fails = scenarios(code, at)
    for f in fails:
        print("FAIL " + f)
    print("%s: the shipped cave, %d bytes, %d failures" % ("ok" if not fails else "FAIL", len(code), len(fails)))
    caught = 0
    for name, old, new in MUTANTS:
        if old not in ASM:
            print("FAIL stale mutant: %s" % name)
            continue
        mcode, mat = assemble(ASM.replace(old, new, 1))
        if scenarios(mcode, mat):
            caught += 1
        else:
            print("FAIL mutant survived: %s" % name)
    print("%d of %d mutants caught" % (caught, len(MUTANTS)))
    return not fails and caught == len(MUTANTS)


